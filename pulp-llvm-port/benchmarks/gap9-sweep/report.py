"""Generates report.md from results.json data (called by run.py; also `python3 report.py`)."""
import collections, json, pathlib, re

CC = ['ref18', 'port19', 'port20', 'gcc']
FAM = ['hwloop', 'postinc', 'p-regoff', 'simd', 'mac', 'clip', 'bitmanip', 'p-other']
SHORT = {'hwloop': 'lp', 'postinc': 'pi', 'p-regoff': 'ro', 'simd': 'pv', 'mac': 'mac', 'clip': 'clip',
         'bitmanip': 'bit', 'p-other': 'p'}


def code(r):
    s, d = r['status'], r['detail'] or ''
    if s == 'ok':
        return 'ok'
    if s == 'crash':
        m = re.search(r"pass '([^']+)' on @?(\S+)", d)
        return f"crash HWLoops ({m.group(2)})" if m and m.group(1) == 'PULP Hardware Loops' else 'crash: ' + d[:60]
    if s == 'assert':
        return 'assert RVV-VLEN' if 'Zve or V' in d else 'assert: ' + d[:60]
    if s == 'timeout':
        return 'timeout'
    if 'outside the valid range' in d:
        return 'Sema RN range'
    m = re.search(r"unknown builtin '(\w+)'", d)
    if m:
        return f'missing builtin {m.group(1)}'
    if "incompatible type 'v2h'" in d:
        return 'missing fp16 builtin (f16abs2)'
    if 'AT_L2_EVENT' in d:
        return 'shim lacks AT_L2_EVENT/DMA'
    return 'error: ' + d[:60]


def mixstr(f):
    m = f.get('mix', {})
    s = ' '.join(f'{SHORT[k]}{m[k]}' for k in FAM if m.get(k))
    if f.get('unknown'):
        s += f' ?{f["unknown"]}'
    return s or '-'


def write(D, meta, rows):
    D = pathlib.Path(D)
    R = {(r['kernel'], r['compiler'], r['opt']): r for r in rows}
    kernels = [k['kernel'] for k in meta['kernels']]
    main = [k for k in kernels if not k.startswith('k12_')]

    def fn(k, c, o, f):
        r = R[(k, c, o)]
        return r['functions'].get(f) if r['status'] == 'ok' else None

    anchor = [k for k in kernels if k.startswith('k12_')]
    L = []
    w = L.append
    w('# GAP9 SDK kernel sweep: static compiler-output comparison\n')
    w('**Static metrics only.** Everything below is compile status, code size and instruction counts read from '
      'object files. Nothing was executed: there are no cycle counts, and no output was checked for correctness. '
      'Instruction-count changes are reported as such and say nothing about speed (loop trip counts, hardware-loop '
      'behaviour and memory latency are not modelled). A simulator is being built separately; see "sim/ hook".\n')
    plan = [k for k in main if not k.endswith('-file') and k != 'clip']
    head = {}
    for c in CC:
        head[c] = {o: (sum(R[(k, c, o)]['status'] == 'ok' for k in plan),
                       sum(R[(k, c, o)]['status'] == 'ok' for k in anchor)) for o in ['O2', 'O3']}
    w('## Summary\n')
    w(f'Kernels that compile, out of {len(plan)} SDK/plan kernel TUs (k01–k11, k10 split into a/b) and {len(anchor)} anchor functions (k12):\n')
    w('| compiler | O2 kernels | O3 kernels | O2 anchor | O3 anchor | clip probe |')
    w('|---|---|---|---|---|---|')
    for c in CC:
        w(f"| {c} | {head[c]['O2'][0]}/{len(plan)} | {head[c]['O3'][0]}/{len(plan)} | {head[c]['O2'][1]}/{len(anchor)} | "
          f"{head[c]['O3'][1]}/{len(anchor)} | {'ok' if all(R[('clip', c, o)]['status'] == 'ok' for o in ['O2', 'O3']) else 'fail'} |")
    both = [(k, o) for k in plan for o in ['O2', 'O3'] if R[(k, 'ref18', o)]['status'] == 'ok' and R[(k, 'port20', o)]['status'] == 'ok']
    newer = sorted(set(k for k in plan + anchor for o in ['O2', 'O3'] if R[(k, 'ref18', o)]['status'] != 'ok' and R[(k, 'port20', o)]['status'] == 'ok'))
    lost = sorted(set(k for k in plan + anchor for o in ['O2', 'O3'] if R[(k, 'ref18', o)]['status'] == 'ok' and R[(k, 'port20', o)]['status'] != 'ok'))
    w('')
    w(f"- ref18 and port20 compile the same plan kernels except: port20 additionally compiles {', '.join(newer) or 'none'}; "
      f"port20 fails where ref18 succeeds: {', '.join(lost) or 'none'}. port19 matches ref18's status everywhere"
      + ('' if all(code(R[(k, 'port19', o)]) == code(R[(k, 'ref18', o)]) for k in kernels for o in ['O2', 'O3']) else ' except where noted in the matrix') + '.')
    dd = []
    for k, o in both:
        for f in R[(k, 'ref18', o)]['functions']:
            a, c = fn(k, 'ref18', o, f), fn(k, 'port20', o, f)
            dd.append(f"{f} {o} {c['size']-a['size']:+d} B / {c['instructions']-a['instructions']:+d} insns")
    w('- port20 − ref18 on kernels both compile: ' + '; '.join(dd) + '. Per-family changes are in the table below.')
    w('- Every failure also happens on ref18 (the fork\'s pre-existing bugs listed in the survey), except the port20 rows noted above; no flags or sources were changed to avoid them.')
    w('- `p.clip` for `clip(x,-128,127)`: all LLVM compilers emit immediate 7, GAP9 GCC emits 8 (see "p.clip immediate").\n')
    w('Generated by `run.py` (which calls `report.py`); raw data in `results.json`, exact commands in `commands.json`, '
      'objects, disassembly, symbol tables and compiler stderr in `build/<compiler>/<opt>/`.\n')
    w('## Setup\n')
    for c in CC:
        w(f"- **{c}**: `{meta['compilers'][c]['path']}` — {meta['compilers'][c]['version']}")
    w(f"- LLVM flags: `{' '.join(meta['llvm_flags'])}`; GCC flags: `{' '.join(meta['gcc_flags'])}` (no `-mint64`: no kernel needed it). "
      'Both at `-O2` and `-O3`, no other code-generation flags (the SDK build additionally uses `-funsigned-char -fno-jump-tables`; omitted for all compilers).')
    w(f"- Includes/defines (all compilers): shim `src/shim/at_api.h` first, then SDK `DSP_Libraries`, `FastMathFunctions`, `Emulation`; "
      f"`-D__gap9__ -D__GAP9__ -D__pulp__`. SDK `{meta['sdk']}` at `{meta['sdk_head'][:12]}`, sources unmodified.")
    w(f"- Disassembly for all objects, GCC's included: `{meta['objdump']}`. `+m` is added because GCC 7 objects carry no "
      '`.riscv.attributes` and `mul` would otherwise decode as `<unknown>`; it does not change the clang objects\' disassembly.')
    w('- Per function: size = symbol size from `llvm-nm -S` (equals the bytes of decoded instructions for every row); '
      'instructions = decoded instructions inside the function (GCC `.L*` labels folded into their function).')
    w('- Mix legend: `lp` hardware loop (`lp.*`), `pi` post-increment load/store (`p.l*`/`p.s*` with `rs!`), '
      '`ro` register-offset `p.l*`/`p.s*` without writeback, `pv` packed SIMD (`pv.*`), `mac` (`p.mac*`/`p.msu*`), '
      '`clip` (`p.clip*`), `bit` (`p.extract/insert/bclr/bset/cnt/ff1/fl1/clb/ror`), `p` other `p.*` (abs/min/max/exths/...), '
      '`?N` = N words port20 llvm-objdump cannot decode (GAP9-only encodings; marks GCC as not like-for-like).\n')

    w('## Corpus\n')
    w('| kernel | source | measured functions |')
    w('|---|---|---|')
    for k in meta['kernels']:
        if k['kernel'].startswith('k12_'):
            continue
        w(f"| {k['kernel']} | {k['source']} | {', '.join(k['functions'])} |")
    w(f"| k12_* ({len(anchor)} TUs) | 19-vs-18/kernels.c, one function per TU as in that study | {', '.join(a[4:] for a in anchor)} |")
    w('\n"extract" = the function(s) copied verbatim by `run.py` into `build/gen/*.extract.c` (with `#line` markers to the SDK file) '
      'because the whole SDK file cannot be compiled for reasons unrelated to the kernel; the whole-file result is kept as the '
      '`-file` row. k03/k04 come from PMSIS apps: the functions are verbatim except a dropped leading `static`; the wrapper maps '
      '`pi_core_id()`/`pi_cl_cluster_nb_cores()`/`gap_fc_readhwtimer()` to constants. `gap_ncore()` is 1 (shim), so all kernels are single-core. '
      'k10a/k10b are the radix-2 FFT loops (scalar and v2s SIMD); runtime twiddle tables are a simulator concern. k11 and clip are written for this sweep.\n')

    w('## Compile status (kernel x compiler)\n')
    w('Cell = status at -O2 and -O3 when equal, otherwise `O2: … / O3: …`.\n')
    w('| kernel | ref18 | port19 | port20 | gcc |')
    w('|---|---|---|---|---|')

    def cell(k, c):
        a, b = code(R[(k, c, 'O2')]), code(R[(k, c, 'O3')])
        return a if a == b else f'O2: {a} / O3: {b}'
    for k in main:
        w(f"| {k} | " + ' | '.join(cell(k, c) for c in CC) + ' |')
    for c_ in [None]:
        cells = []
        for c in CC:
            n2 = sum(R[(k, c, 'O2')]['status'] == 'ok' for k in anchor)
            n3 = sum(R[(k, c, 'O3')]['status'] == 'ok' for k in anchor)
            cells.append(f'{n2}/{len(anchor)} ok' if n2 == n3 else f'O2 {n2} / O3 {n3} of {len(anchor)} ok')
        w(f"| k12_* anchor | " + ' | '.join(cells) + ' |')
    w('')
    counts = collections.OrderedDict()
    for c in CC:
        counts[c] = {o: sum(R[(k, c, o)]['status'] == 'ok' for k in kernels) for o in ['O2', 'O3']}
    w(f'Totals (TUs that compile, out of {len(kernels)} at each level, anchor functions counted individually): ' +
      '; '.join(f"{c} O2 {v['O2']}, O3 {v['O3']}" for c, v in counts.items()) + '.\n')
    fails = collections.defaultdict(list)
    for r in rows:
        if r['status'] != 'ok' and r['kernel'] not in anchor:
            fails[(r['status'], r['detail'])].append(f"{r['kernel']} {r['compiler']} {r['opt']}")
    anchor_fail = collections.defaultdict(list)
    for r in rows:
        if r['status'] != 'ok' and r['kernel'] in anchor:
            anchor_fail[(r['status'], re.sub(r'@\w+', '@<fn>', r['detail']))].append(f"{r['kernel'][4:]} {r['compiler']} {r['opt']}")
    w('Failure details (first diagnostic line or crash location, from `build/<cc>/<opt>/<kernel>.stderr`):\n')
    for (s, d), where in list(fails.items()) + list(anchor_fail.items()):
        w(f"- **{s}**: `{d}` — {', '.join(where)}")
    w('')

    # ---------------- comparison tables
    def fmt(x, key):
        return '—' if x is None else str(x[key])

    w('## port20 vs ref18 (and port19), GCC as reference\n')
    w('Only kernels that compile on both ref18 and port20 at that level. Sizes in bytes. '
      '"LLVM mix" is ref18 / port19 / port20 (one entry when identical). Δ columns are port20 − ref18.\n')
    w('| kernel | opt | function | bytes ref18/port19/port20 | Δbytes | insns ref18/port19/port20 | Δinsns | LLVM mix | GCC bytes / insns | GCC mix | note |')
    w('|---|---|---|---|---|---|---|---|---|---|---|')
    anchor_same = collections.Counter()
    for k in main + anchor:
        for o in ['O2', 'O3']:
            if R[(k, 'ref18', o)]['status'] != 'ok' or R[(k, 'port20', o)]['status'] != 'ok':
                continue
            for f in R[(k, 'ref18', o)]['functions']:
                a, b, c, g = (fn(k, cc, o, f) for cc in CC)
                mixes = [mixstr(x) if x else '—' for x in (a, b, c)]
                same = (a['size'], a['instructions'], a.get('mix')) == (c['size'], c['instructions'], c.get('mix')) and \
                       b is not None and (b['size'], b['instructions'], b.get('mix')) == (a['size'], a['instructions'], a.get('mix'))
                if k in anchor and same and g and (g['size'], g['instructions'], g.get('mix')) == (a['size'], a['instructions'], a.get('mix')):
                    anchor_same[o] += 1
                    continue
                note = ''
                if g is None:
                    note = 'GCC failed'
                elif g.get('unknown'):
                    note = 'GCC not like-for-like (GAP9-only insns)'
                w(f"| {k} | {o} | {f} | {fmt(a,'size')}/{fmt(b,'size')}/{fmt(c,'size')} | {c['size']-a['size']:+d} | "
                  f"{fmt(a,'instructions')}/{fmt(b,'instructions')}/{fmt(c,'instructions')} | {c['instructions']-a['instructions']:+d} | "
                  f"{mixes[0] if len(set(mixes)) == 1 else ' / '.join(mixes)} | "
                  f"{fmt(g,'size')} / {fmt(g,'instructions')} | {mixstr(g) if g else '—'} | {note} |")
    if anchor_same:
        w(f"\nNot listed: anchor functions identical in bytes, instructions and mix on all four compilers "
          f"(O2: {anchor_same['O2']}, O3: {anchor_same['O3']}).")
    w('')

    w('## Kernels that compile on port20 but not on ref18\n')
    w('No ref18 baseline exists for these (ref18 crashes), so they are not port regressions or wins; listed with GCC for reference.\n')
    w('| kernel | opt | function | port19 | port20 bytes / insns | port20 mix | GCC bytes / insns | GCC mix | note |')
    w('|---|---|---|---|---|---|---|---|---|')
    for k in main + anchor:
        for o in ['O2', 'O3']:
            if R[(k, 'ref18', o)]['status'] == 'ok' or R[(k, 'port20', o)]['status'] != 'ok':
                continue
            for f in R[(k, 'port20', o)]['functions']:
                c, g = fn(k, 'port20', o, f), fn(k, 'gcc', o, f)
                p19 = code(R[(k, 'port19', o)])
                note = 'GCC not like-for-like (GAP9-only insns)' if g and g.get('unknown') else ''
                w(f"| {k} | {o} | {f} | {p19} | {c['size']} / {c['instructions']} | {mixstr(c)} | "
                  f"{fmt(g,'size')} / {fmt(g,'instructions')} | {mixstr(g) if g else '—'} | {note} |")
    w('')

    w('## GCC-only rows with GAP9-only instructions\n')
    ll = []
    for k in main:
        for o in ['O2', 'O3']:
            r = R[(k, 'gcc', o)]
            if r['status'] == 'ok':
                for f, v in r['functions'].items():
                    if v.get('unknown'):
                        ll.append(f'{k} {o} {f} ({v["unknown"]} undecodable words)')
    w(('Not like-for-like with any LLVM row: ' + '; '.join(ll) + '.') if ll else 'None among measured functions.')
    w('')

    w('## p.clip immediate\n')
    w('`clip.c`: `__builtin_pulp_clip(x,-128,127)` and `__builtin_pulp_clipu(x,0,255)`. Operand as printed by port20 llvm-objdump.\n')
    w('| function | opt | ref18 | port19 | port20 | gcc |')
    w('|---|---|---|---|---|---|')
    for f in ['clip_s8', 'clipu_u8']:
        for o in ['O2', 'O3']:
            w(f"| {f} | {o} | " + ' | '.join(', '.join(fn('clip', c, o, f)['clip_operands']) for c in CC) + ' |')
    s8 = {c: fn('clip', c, 'O2', 'clip_s8')['clip_operands'] for c in CC}
    w('')
    w(f"For `[-128,127]` the three LLVM compilers encode `{s8['port20'][0].split(',')[-1].strip()}` and GAP9 GCC encodes "
      f"`{s8['gcc'][0].split(',')[-1].strip()}`; for `clipu [0,255]` all four agree. With GVSoC's `p.clip` semantics "
      '(clamp to `[-2^(N-1), 2^(N-1)-1]`, per the survey) the LLVM immediate would clamp to `[-64,63]`. This is inherited from ref18 '
      '(port19 and port20 match it) and is unconfirmed until run on the simulator. The same one-lower immediate appears in real SDK code: '
      '`gap_clip(x,15)` expands to `__builtin_pulp_clip(x,-32768,32767)`; in k05 `KerParMatMulDSP_Fix16` the LLVM compilers encode 0xf and GCC 0x10 '
      '(k07 `KerParMatAdd_DSP_Fix16` also uses it but crashes all LLVM compilers). '
      + clip_in_kernels(rows) + '\n')

    w('## sim/ hook\n')
    w('This sweep produces objects only and does not read or write `sim/`, which belongs to the separate simulator work '
      '(target gvsoc2 `ri5ky_testbench`, survey sections 3 and 5). To time these objects the runtime harness needs, per kernel:\n')
    w('- a fixed input set: deterministic data (seeded PRNG or tables) sized per kernel, e.g. FIR taps + samples (k01/k02), '
      'int16/fp32 matrices with dimensions (k03–k07), pre-emphasis/window buffers (k08), complex int16 vectors (k09), '
      'N-point complex data plus a small Q15 twiddle table (k10a/k10b), int8 vectors (k11), and scalar inputs spanning the clip bounds (clip.c);')
    w('- a call stub that fills the kernel\'s argument struct (`KerFirSeq`, `MatMul_DSP_T`, `KerMatAdd_DSP_T`, ...) and calls the kernel object built here, unchanged;')
    w('- a result checksum over the output buffer (e.g. CRC32 or 64-bit sum), with a golden value from GCC\'s object and/or a host build, '
      'compared exactly for integer kernels and with a stated tolerance for fp32;')
    w('- cycle readout around N repetitions via the testbench MMIO counter (`0x10000008`/`0x1000000C`), one shared harness/crt0/link script, only the kernel `.o` changing per compiler;')
    w('- the clip probe first: its checksum decides whether `p.clip ...,7` is a miscompile before any `gap_clip` kernel is timed.\n')
    w('## Reproduce\n')
    w('`python3 run.py` (from any directory; deletes and rebuilds `build/`, rewrites `results.json`, `commands.json`, `report.md`; about 5 s on 16 threads). Rerunning reproduces `report.md` and all metrics exactly; clang objects are bit-identical, GAP9 GCC objects differ only in a per-compile `nonce=` string outside `.text`.')
    (D / 'report.md').write_text('\n'.join(L) + '\n')


def clip_in_kernels(rows):
    seen = []
    for r in rows:
        if r['status'] != 'ok' or r['kernel'] == 'clip' or r['kernel'].endswith('-file'):
            continue
        for f, v in r['functions'].items():
            ops = v.get('clip_operands')
            if ops:
                imms = sorted(set(o.split(',')[-1].strip() for o in ops))
                seen.append(f"{r['kernel']} {r['compiler']} {r['opt']}: {len(ops)}x p.clip, imm {'/'.join(imms)}")
    return ('Other measured functions containing `p.clip` (their source is `gap_clip(x,15)`, i.e. `clip(x,-32768,32767)`): '
            + '; '.join(seen) + '.') if seen else 'No other measured function contains `p.clip`.'


if __name__ == '__main__':
    D = pathlib.Path(__file__).resolve().parent
    j = json.loads((D / 'results.json').read_text())
    write(D, j['meta'], j['rows'])
