#!/usr/bin/env bash
# Build the test-6 kernel library (12 GAP9 SDK / sweep kernels + their drivers) with one compiler.
#   kernels/build_kernels.sh <gcc|clang> <O2|O3> <out dir> [compiler binary]
# Output: <out dir>/libpack_kernels.a (+ build.log, *.o, disassembly kernels.dis).
# Flags are the GVSoC sweep's (benchmarks/gap9-sweep/run.py) so checksums and code match:
#   gcc  : riscv32-unknown-elf-gcc -march=rv32imcxgap9 -mPE=8 -mFC=1 -O2
#   clang: clang --target=riscv32-unknown-elf -march=rv32imc_xgap9 -mabi=ilp32 -mno-relax -O2
#          -isystem <GAP9 GCC newlib include>
# Needs GAP_SDK_HOME (the SDK's DSP library sources are #included by some kernels) and the GAP9
# GCC toolchain on PATH (riscv32-unknown-elf-gcc / -ar; newlib headers for clang).
# A kernel that does not compile is left out of the library (logged); main.c prints which ran.
set -uo pipefail
CC_KIND=${1:?gcc|clang}; OPT=${2:?O2|O3}; OUT=${3:?out dir}; CC=${4:-}
HERE=$(cd "$(dirname "$0")" && pwd)
: "${GAP_SDK_HOME:?source the GAP9 SDK config first}"
GCC_BIN=$(command -v riscv32-unknown-elf-gcc) || { echo "riscv32-unknown-elf-gcc not on PATH" >&2; exit 2; }
GCCTC=$(cd "$(dirname "$GCC_BIN")/.." && pwd)
AR=$GCCTC/bin/riscv32-unknown-elf-ar
AT=$GAP_SDK_HOME/tools/autotiler_v3; DSP=$AT/BasicKernels/DSP_Libraries
KERNELS="k01_fir_fix16 k02_fir_f32 k03_matmul_worker_i16 k04_matmul_simple_f32 k05_matmul_dsp_fix16
         k06_matvect_dsp_f32 k09_cmplx_fix k10a_fft_radix2_scalar k11_dotprod_i8 clip k12_dot16_loop k12_copy_loop"
case $CC_KIND in
  gcc)   CC=${CC:-$GCC_BIN}; BASE=(-march=rv32imcxgap9 -mPE=8 -mFC=1) ;;
  clang) CC=${CC:?clang: give the clang binary as 4th argument}
         BASE=(--target=riscv32-unknown-elf -march=rv32imc_xgap9 -mabi=ilp32 -mno-relax -isystem "$GCCTC/riscv32-unknown-elf/include") ;;
  *) echo "compiler kind must be gcc or clang" >&2; exit 2 ;;
esac
INC=(-I"$HERE/shim" -I"$HERE/gen" -I"$DSP" -I"$DSP/FastMathFunctions" -I"$AT/Emulation" -D__gap9__ -D__GAP9__ -D__pulp__)
DRV=(-ffreestanding -fno-builtin -I"$HERE")
mkdir -p "$OUT"; OUT=$(cd "$OUT" && pwd); rm -f "$OUT"/*.o "$OUT/libpack_kernels.a"
LOG=$OUT/build.log; : > "$LOG"
ok=()
for k in $KERNELS; do
  sym=${k}_main
  echo "== $k" >> "$LOG"
  if "$CC" "${BASE[@]}" -"$OPT" "${INC[@]}" -c "$HERE/src/$k.c" -o "$OUT/$k.kernel.o" >> "$LOG" 2>&1 &&
     "$CC" "${BASE[@]}" -"$OPT" "${DRV[@]}" -Dmain="$sym" -c "$HERE/drivers/$k.c" -o "$OUT/$k.driver.o" >> "$LOG" 2>&1; then
    ok+=("$k")
  else
    echo "COMPILE FAILED: $k (see $LOG)"; rm -f "$OUT/$k.kernel.o" "$OUT/$k.driver.o"
  fi
done
{
  echo "/* generated by build_kernels.sh */"
  for k in "${ok[@]}"; do echo "int ${k}_main(void);"; done
  echo "typedef struct { const char *name; int (*main)(void); } pack_kernel_t;"
  echo "const pack_kernel_t pack_kernels[] = {"
  for k in "${ok[@]}"; do echo "  { \"$k\", ${k}_main },"; done
  echo "};"
  echo "const int pack_nkernels = ${#ok[@]};"
  echo "const char pack_kernels_lib[] = \"$CC_KIND-$OPT\";"
  echo "const char pack_kernels_id[] = \"$CC_KIND -$OPT: \" __VERSION__;"
} > "$OUT/pack_kernels_list.c"
"$CC" "${BASE[@]}" -"$OPT" -c "$OUT/pack_kernels_list.c" -o "$OUT/pack_kernels_list.o" >> "$LOG" 2>&1 || exit 3
"$AR" rcs "$OUT/libpack_kernels.a" "$OUT"/*.o || exit 3
"$GCCTC/bin/riscv32-unknown-elf-objdump" -d "$OUT"/*.kernel.o > "$OUT/kernels.dis" 2>/dev/null || true
echo "built $OUT/libpack_kernels.a with ${#ok[@]} kernels ($CC_KIND -$OPT)"
