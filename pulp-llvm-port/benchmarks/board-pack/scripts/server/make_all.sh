#!/usr/bin/env bash
# Server-side only: build every prebuilt ELF of the pack for the board platform, run each one on
# GVSoC2 gap.gap9.evk (the board ELFs run there unchanged) and record the output as the
# "simulator result" in sim-results/. Also builds the clang kernel libraries for test 6.
#   SDK_CLANG_WORK=<sdk-clang work dir> scripts/server/make_all.sh <scratch build dir>
# Needs benchmarks/sdk-clang/setup.sh to have been run (SDK mirror, venv, GVSoC2, clang snapshot).
set -o pipefail
PACK=$(cd "$(dirname "$0")/../.." && pwd)
OUT=${1:?scratch build dir}; mkdir -p "$OUT"; OUT=$(cd "$OUT" && pwd)
source "$PACK/scripts/server/env.sh"
export GAP_CLANG_ROOT=${GAP_CLANG_ROOT:-$SDK_CLANG_WORK/snap}
CLANG=$GAP_CLANG_ROOT/bin/clang
RUN=/home/ubuntu/llvm-project/pulp-llvm-port/benchmarks/sdk-clang/run_app.sh
PB=$PACK/prebuilt; SR=$PACK/sim-results
mkdir -p "$PB/board" "$PB/kernels" "$SR"
ok() { echo "[make_all] $*"; }
put() {  # put <elf> <name>: copy to prebuilt/board/<name>.elf and run it on GVSoC
  cp "$1" "$PB/board/$2.elf"
  bash "$RUN" "$PB/board/$2.elf" 900 > "$SR/$2.log" 2>&1
  ok "$2: sim exit $? ($(grep -c '^CHECK.*PASS' "$SR/$2.log") PASS, $(grep -c '^CHECK.*FAIL' "$SR/$2.log") FAIL)"
}
# tests 1-5 and 8 (GAP9 GCC only)
for t in t1_b101_gcc_hwloop t2_hwloop_align_b68 t3_fp16_vcmp_lanes_b99 t4_shuffle_sci_h_b114 t5_shuffle2_order_b113 \
         t8_vfmre_sign_b151; do
  "$PACK/scripts/build.sh" "$PACK/$t" board "$OUT/$t" > "$OUT/$t.build.log" 2>&1 || { ok "$t BUILD FAILED"; continue; }
  put "$OUT/$t/$t" "$t"
done
# test 6: kernel libraries, then one app per library
for v in gcc-O2 gcc-O3 clang-O2 clang-O3; do
  kind=${v%-*}; opt=${v#*-}
  cc=""; [ "$kind" = clang ] && cc=$CLANG
  "$PACK/t6_kernels_clang_vs_gcc/kernels/build_kernels.sh" "$kind" "$opt" "$OUT/klib-$v" $cc || { ok "klib $v FAILED"; continue; }
  mkdir -p "$PB/kernels/$v"
  cp "$OUT/klib-$v/libpack_kernels.a" "$OUT/klib-$v/kernels.dis" "$OUT/klib-$v/build.log" "$PB/kernels/$v/"
  "$PACK/scripts/build.sh" "$PACK/t6_kernels_clang_vs_gcc" board "$OUT/t6-$v" -DPACK_KERNELS_LIB="$OUT/klib-$v/libpack_kernels.a" \
    > "$OUT/t6-$v.build.log" 2>&1 || { ok "t6 $v BUILD FAILED"; continue; }
  put "$OUT/t6-$v/t6_kernels_clang_vs_gcc" "t6_kernels.$v"
done
# test 7: SDK examples and the core-count app, all-GCC and all-clang
for v in gcc clang clang-ccfix; do
  for a in "$GAP_SDK_HOME/examples/gap9/basic/helloworld" "$GAP_SDK_HOME/examples/gap9/basic/perf" "$PACK/t7_sdk_apps_clang/t7_corecount"; do
    n=$(basename "$a")
    "$PACK/t7_sdk_apps_clang/build_clang_app.sh" "$a" board "$OUT/t7-$n-$v" "$v" > "$OUT/t7-$n-$v.build.log" 2>&1 || { ok "t7 $n $v BUILD FAILED"; continue; }
    put "$OUT/t7-$n-$v/$n" "t7_${n#t7_}.$v"
  done
done
# manifest
{
  echo "# prebuilt/ manifest (generated by scripts/server/make_all.sh on $(date -u +%Y-%m-%dT%H:%MZ))"
  echo "# GAP9 SDK $(cat /home/ubuntu/gap_sdk_release/sdk_version 2>/dev/null || echo 5.21.14), config gap9_evk_audio (CONFIG_BOARD_GAP9EVK_V1_3), CONFIG_PLATFORM_BOARD=y"
  echo "# GAP9 GCC: $(riscv32-unknown-elf-gcc --version | head -1)"
  echo "# clang: $("$CLANG" --version | head -1)"
  echo "# sha256  file"
  (cd "$PB" && find board kernels -type f | sort | xargs sha256sum)
} > "$PB/MANIFEST.txt"
ok "done: $(ls "$PB/board" | wc -l) ELFs"
