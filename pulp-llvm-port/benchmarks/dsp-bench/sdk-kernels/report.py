"""Builds report.txt (Markdown content) from results.json (+ the hand-written analysis.txt). Called by run.py."""
import collections, json, math, pathlib


def gm(xs):
    xs = [x for x in xs if x and x > 0]
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else None


def f3(x):
    return '-' if x is None else f'{x:.3f}'


def summarize(data):
    """All derived numbers used by the report and by the final message."""
    rows = data['rows']
    idx = {(r['kernel'], r['compiler'], r['opt']): r for r in rows}
    kernels = list(collections.OrderedDict((r['kernel'], r) for r in rows if r['compiler'] == 'gcc').values())
    opts = data['meta']['opts']
    S = dict(opts=opts, kernels=kernels, idx=idx)
    ratio, iratio = {}, {}
    for k in kernels:
        for o in opts:
            c, g = idx.get((k['kernel'], 'clang', o)), idx.get((k['kernel'], 'gcc', o))
            if c and g and c['status'] == 'ok' and g['status'] == 'ok':
                ratio[(k['kernel'], o)] = c['cycles'] / g['cycles']
                iratio[(k['kernel'], o)] = c['instrs'] / g['instrs']
    S['ratio'], S['iratio'] = ratio, iratio
    # function level: geomean over the sizes of one function (one kernel x data type counts once)
    fr = collections.defaultdict(list)
    for (kn, o), v in ratio.items():
        r = idx[(kn, 'gcc', o)]
        fr[(r['app'], r['function'], r['dt'], r['category'], o)].append(v)
    S['fratio'] = {k: gm(v) for k, v in fr.items()}
    return S


def write(R, data):
    R = pathlib.Path(R)
    S = summarize(data)
    rows, idx, kernels, opts, ratio = data['rows'], S['idx'], S['kernels'], S['opts'], S['ratio']
    m = data['meta']
    L = []
    A = L.append
    A('# GAP9 SDK DSP benchmark kernels: our clang vs GAP9 GCC (single core, GVSoC)\n')
    A('(Markdown content. Saved as report.txt because the Write tool refuses .md files in this harness.)\n')
    A('Generated by `run.py` / `report.py` from `results.json`; the "Analysis" section is hand-written (`analysis.txt`).\n')
    apprs = [k for k in kernels if k['category'] == 'app']
    funcs = collections.OrderedDict(((k['app'], k['function'], k['dt'], k['category']), 1) for k in kernels)

    def count(comp, o, pred, ks=kernels):
        return sum(1 for k in ks if (k['kernel'], comp, o) in idx and pred(idx[(k['kernel'], comp, o)]))

    # ------------------------------------------------------------------ headline
    A('## Headline\n')
    A(f'- **Configurations measured:** {len(kernels)} kernel x data type x problem size, from {len(funcs)} kernel functions '
      f'({sum(1 for f in funcs if f[3] == "app")} of them in configurations the six benchmark apps run or can be Kconfig\'d to run; '
      f'{sum(1 for f in funcs if f[3] != "app")} are data-type variants of the same library files that the apps cannot select: '
      'every f16alt kernel, and MatMul fix16/f16).')
    for o in opts:
        okc = count('clang', o, lambda r: r['status'] == 'ok')
        nl = count('clang', o, lambda r: r['status'].startswith('does not link'))
        wr = count('clang', o, lambda r: r['status'] == 'WRONG')
        other = len(kernels) - okc - nl - wr
        okg = count('gcc', o, lambda r: r['status'] == 'ok')
        wg = count('gcc', o, lambda r: r['status'] == 'WRONG')
        A(f'- **-{o} correctness.** clang: {okc} correct, {wr} wrong, {nl} do not link (B133, all f16alt){", %d other" % other if other else ""}. '
          f'GCC: {okg} correct, {wg} wrong (see "GCC f16 RFFT" below).')
    A('')
    A('| opt | geomean clang/gcc cycles, per kernel function | same, app configurations only | geomean over all (kernel, size) rows | rows compared | clang faster (>1%) | within 1% | clang slower (>1%) |')
    A('|---|---|---|---|---|---|---|---|')
    for o in opts:
        fa = [v for k, v in S['fratio'].items() if k[4] == o]
        fapp = [v for k, v in S['fratio'].items() if k[4] == o and k[3] == 'app']
        rr = [v for (kn, oo), v in ratio.items() if oo == o]
        A(f'| -{o} | **{f3(gm(fa))}** ({len(fa)} functions) | {f3(gm(fapp))} ({len(fapp)}) | {f3(gm(rr))} | {len(rr)} | '
          f'{sum(1 for v in rr if v < 0.99)} | {sum(1 for v in rr if 0.99 <= v <= 1.01)} | {sum(1 for v in rr if v > 1.01)} |')
    A('\nA ratio below 1 means clang needs fewer cycles than GCC. Only configurations where both builds ran and gave a correct result are compared.\n')

    # ------------------------------------------------------------------ setup
    A('## What was measured\n')
    A(f'- **Ours:** `{m["compilers"]["clang"]["version"]}`  \n  flags: `{" ".join(m["clang_flags"])}`')
    A(f'- **Reference:** `{m["compilers"]["gcc"]["version"]}`  \n  flags: `{" ".join(m["gcc_flags"])}`')
    A(f'- **Both:** `{" ".join(m["sdk_cflags"])}` (the SDK\'s code-generation flags from `utils/cmake/gcc_flags.cmake`), opt levels {", ".join("-" + o for o in opts)}, `-D__GAP9__`.')
    A('- **Sources:** the SDK DSP library files, whole and unmodified, with the one-core shim `shim/at_api.h` (it includes `gap9-sweep/src/shim/at_api.h`). Twiddle/swap tables are the SDK\'s LUT files. Inputs come from each app\'s own generator (`InitData.c`, `gen_test_data.py`), run by `run.py` into `gen/`.')
    A(f'- **Simulator:** {m["simulator"]}. One warm-up call, then {m["rt_reps"]} timed calls (2 for the 128x256x128 MatMul); cycles = simulator cycle counter, instructions = RI5CY PCCR1, both per call.')
    A(f'- **Host reference:** `{m["host_cc"]}`, `-O0`, the same drivers and SDK sources through the SDK\'s `__EMUL__` plain-C branch (`hostshim/at_api.h`).')
    A('- **Correctness rule.** "correct" = the FNV-1a checksum of the output buffer(s) equals the host reference\'s, or, for float kernels that are not bit-exact, '
      'the largest output error divided by the largest reference value is within the tolerance: '
      + ', '.join(f'{k} {v:g}' for k, v in m['tolerance'].items()) + '. The same comparison is made against the GCC build of the same opt level.')
    A('- **Code size:** bytes of the kernel function plus every DSP-library function it calls (found through the relocations), from the `-ffunction-sections` objects.\n')

    # ------------------------------------------------------------------ correctness matrix
    A('## Correctness\n')
    A('Counts of (kernel, size) configurations. "exact" = bit-exact with the host reference; "tol" = float, within tolerance of the host; "=gcc" = bit-exact with the GCC build of the same opt level.\n')
    A('| app | data type | category | n | ' + ' | '.join(f'clang -{o}' for o in opts) + ' | ' + ' | '.join(f'gcc -{o}' for o in opts) + ' |')
    A('|---|---|---|---|' + '---|' * (2 * len(opts)))
    groups = collections.OrderedDict()
    for k in kernels:
        groups.setdefault((k['app'], k['dt'], k['category']), []).append(k)

    def cell(ks, comp, o):
        c = collections.Counter()
        eqg = 0
        for k in ks:
            r = idx.get((k['kernel'], comp, o))
            if not r:
                c['missing'] += 1
            elif r['status'] == 'ok':
                c['exact' if r.get('exact_vs_host') else 'tol'] += 1
                eqg += bool(r.get('exact_vs_gcc'))
            else:
                c[r['status']] += 1
        s = ', '.join(f'{v} {k}' for k, v in c.items())
        if comp == 'clang' and (c['exact'] or c['tol']):
            s += f' ({eqg} =gcc)'
        return s
    for (app, dt, cat), ks in groups.items():
        A(f'| {app} | {dt} | {cat} | {len(ks)} | ' + ' | '.join(cell(ks, 'clang', o) for o in opts) + ' | ' + ' | '.join(cell(ks, 'gcc', o) for o in opts) + ' |')
    A('')
    A('Largest float error against the host reference and against GCC, per data type (max over all correct configurations; error = max abs difference / largest reference value; '
      'the "vs gcc" columns leave out the configurations where GCC itself is wrong):\n')
    A('| data type | compiler | ' + ' | '.join(f'-{o} vs host' for o in opts) + ' | ' + ' | '.join(f'-{o} vs gcc' for o in opts) + ' |')
    A('|---|---|' + '---|' * (2 * len(opts)))
    for dt in ['f32', 'f16', 'f16a']:
        for comp in ['clang', 'gcc', 'clang+rt']:
            rs = [r for r in rows if r['dt'] == dt and r['compiler'] == comp and r['status'] == 'ok']
            if not rs:
                continue
            def mx(o, key):
                v = [r.get(key) or 0.0 for r in rs if r['opt'] == o and
                     (key != 'err_vs_gcc' or idx[(r['kernel'], 'gcc', o)]['status'] == 'ok')]
                return f'{max(v):.1e}' if v else '-'
            A(f'| {dt} | {comp} | ' + ' | '.join(mx(o, 'err_vs_host') for o in opts) + ' | ' +
              ' | '.join(mx(o, 'err_vs_gcc') if comp != 'gcc' else '-' for o in opts) + ' |')
    A('')
    bad = [r for r in rows if r['status'] not in ('ok',) and not r['status'].startswith('does not link')]
    if bad:
        A('Rows that are not "ok" (other than the B133 link failures, listed in their own section):\n')
        A('| kernel | compiler | opt | status | detail |')
        A('|---|---|---|---|---|')
        seen = collections.OrderedDict()
        for r in bad:
            key = (r['app'], r['function'], r['compiler'], r['status'])
            seen.setdefault(key, []).append(r)
        for (app, fn, comp, st), rs in seen.items():
            os_ = sorted({r['opt'] for r in rs})
            ns = sorted({r['size_n'] for r in rs if r['size_n']})
            d = (rs[0].get('verdict') or rs[0].get('reason') or '')[:160].replace('|', '/').replace('\n', ' ')
            A(f'| {app}.{fn} (N={",".join(map(str, ns))}) | {comp} | {",".join(os_)} | {st} | {d} |')
        A('')

    # ------------------------------------------------------------------ speed
    A('## Speed: clang/gcc cycle ratio\n')
    A('Geometric means. "functions" = each kernel function x data type counts once (its sizes are averaged first); "rows" = every (kernel, size) counts once.\n')
    A('| group | ' + ' | '.join(f'-{o} functions' for o in opts) + ' | ' + ' | '.join(f'-{o} rows' for o in opts) + ' |')
    A('|---|' + '---|' * (2 * len(opts)))

    def grow(label, fpred, rpred):
        fs = [f3(gm([v for k, v in S['fratio'].items() if k[4] == o and fpred(k)])) + f' ({sum(1 for k in S["fratio"] if k[4] == o and fpred(k))})' for o in opts]
        rs = [f3(gm([v for (kn, oo), v in ratio.items() if oo == o and rpred(idx[(kn, "gcc", o)])])) for o in opts]
        A(f'| {label} | ' + ' | '.join(fs) + ' | ' + ' | '.join(rs) + ' |')
    grow('**all**', lambda k: True, lambda r: True)
    grow('app configurations', lambda k: k[3] == 'app', lambda r: r['category'] == 'app')
    for dt in ['fix16', 'f32', 'f16', 'f16a']:
        grow(f'data type {dt}', lambda k, dt=dt: k[2] == dt, lambda r, dt=dt: r['dt'] == dt)
    for app in collections.OrderedDict((k['app'], 1) for k in kernels):
        grow(f'app {app}', lambda k, app=app: k[0] == app, lambda r, app=app: r['app'] == app)
    A('\n(number of functions in brackets; "-" = nothing comparable, e.g. f16alt, where clang does not link)\n')

    A('### Per kernel function (geomean over its problem sizes)\n')
    A('| app | function | type | category | sizes | ' + ' | '.join(f'-{o} cycles' for o in opts) + ' | ' + ' | '.join(f'-{o} instrs' for o in opts) + ' | note |')
    A('|---|---|---|---|---|' + '---|' * (2 * len(opts)) + '---|')
    for (app, fn, dt, cat) in funcs:
        ks = [k for k in kernels if (k['app'], k['function'], k['dt']) == (app, fn, dt)]
        ns = [k['size_n'] for k in ks]
        cy = [f3(gm([ratio.get((k['kernel'], o)) for k in ks])) for o in opts]
        ins = [f3(gm([S['iratio'].get((k['kernel'], o)) for k in ks])) for o in opts]
        note = set()
        for k in ks:
            for o in opts:
                c, g = idx.get((k['kernel'], 'clang', o)), idx.get((k['kernel'], 'gcc', o))
                if c and c['status'] != 'ok':
                    note.add('clang: ' + c['status'])
                if g and g['status'] != 'ok':
                    note.add('gcc: ' + g['status'])
        A(f'| {app} | {fn} | {dt} | {cat} | {ns[0]}..{ns[-1]} ({len(ns)}) | ' + ' | '.join(cy) + ' | ' + ' | '.join(ins) + f' | {"; ".join(sorted(note))} |')
    A('')
    for o in opts:
        fl = sorted(((v, k) for k, v in S['fratio'].items() if k[4] == o), key=lambda t: t[0])
        if not fl:
            continue
        A(f'**-{o}: best for clang** ' + '; '.join(f'{k[1]} {f3(v)}' for v, k in fl[:6]) + '  ')
        A(f'**-{o}: worst for clang** ' + '; '.join(f'{k[1]} {f3(v)}' for v, k in fl[-6:][::-1]) + '\n')

    # ------------------------------------------------------------------ size
    A('## Code size (kernel function + the library functions it calls, bytes)\n')
    A('| app | function | type | ' + ' | '.join(f'gcc -{o} | clang -{o} | ratio' for o in opts) + ' |')
    A('|---|---|---|' + '---|---|---|' * len(opts))
    sr = collections.defaultdict(list)
    for (app, fn, dt, cat) in funcs:
        k = next(k for k in kernels if (k['app'], k['function'], k['dt']) == (app, fn, dt))
        cells = []
        for o in opts:
            c, g = idx.get((k['kernel'], 'clang', o)), idx.get((k['kernel'], 'gcc', o))
            cb, gb = (c or {}).get('code_bytes'), (g or {}).get('code_bytes')
            if cb and gb:
                sr[o].append(cb / gb)
                sr[(o, dt)].append(cb / gb)
                if cat == 'app':
                    sr[(o, 'app')].append(cb / gb)
            cells.append(f'{gb or "-"} | {cb or "-"} | {f3(cb / gb) if cb and gb else "-"}')
        A(f'| {app} | {fn} | {dt} | ' + ' | '.join(cells) + ' |')
    A('')
    A('| geomean clang/gcc size | ' + ' | '.join(f'-{o}' for o in opts) + ' |')
    A('|---|' + '---|' * len(opts))
    A('| all functions | ' + ' | '.join(f3(gm(sr[o])) for o in opts) + ' |')
    A('| app configurations | ' + ' | '.join(f3(gm(sr[(o, "app")])) for o in opts) + ' |')
    for dt in ['fix16', 'f32', 'f16', 'f16a']:
        A(f'| {dt} | ' + ' | '.join(f3(gm(sr[(o, dt)])) for o in opts) + ' |')
    A('\nSize is a static property, so the f16alt functions are included here even though clang\'s f16alt programs do not link.\n')
    S['size'] = {str(k): gm(v) for k, v in sr.items()}

    # ------------------------------------------------------------------ B133
    nl = [r for r in rows if r['status'].startswith('does not link')]
    A('## f16alt (bfloat16): does not link (B133)\n')
    if nl:
        fns = collections.OrderedDict()
        for r in nl:
            fns.setdefault((r['app'], r['function']), set()).update(r.get('truncsfbf2_refs') or [])
        A(f'With clang, **{len({(r["kernel"]) for r in nl})} f16alt configurations ({len(fns)} kernel functions) do not link at any opt level**: the objects call `__truncsfbf2`, '
          'which GAP9 libgcc does not have (BACKLOG B133). GCC links and runs all of them. Functions whose code references `__truncsfbf2` (-O2 objects):\n')
        A('| app | kernel function | library functions in its call tree that call `__truncsfbf2` |')
        A('|---|---|---|')
        for (app, fn), refs in fns.items():
            A(f'| {app} | {fn} | {", ".join(sorted(refs)) or "none: this function would link by itself; it is not run because the driver times it together with the FFT that feeds it"} |')
        A('')
    rt = [r for r in rows if r['compiler'] == 'clang+rt']
    if rt:
        A('### Separate experiment, not part of any number above: clang + compiler-rt `__truncsfbf2`\n')
        A('The same clang objects linked with `compiler-rt/lib/builtins/truncsfbf2.c` (built by the same clang). This shows that the code is functionally right and what the '
          'soft-float detour costs. It is **not** a supported configuration, and these rows are in no geomean.\n')
        A('| app | function | sizes | correct | ' + ' | '.join(f'-{o} cycles clang+rt/gcc' for o in opts) + ' |')
        A('|---|---|---|---|' + '---|' * len(opts))
        fg = collections.OrderedDict()
        for r in rt:
            fg.setdefault((r['app'], r['function']), []).append(r)
        allr = collections.defaultdict(list)
        for (app, fn), rs in fg.items():
            cells = []
            for o in opts:
                v = []
                for r in rs:
                    g = idx.get((r['kernel'], 'gcc', o))
                    if r['opt'] == o and r['status'] == 'ok' and g and g['status'] == 'ok':
                        v.append(r['cycles'] / g['cycles'])
                allr[o] += v
                cells.append(f3(gm(v)))
            okn = sum(1 for r in rs if r['status'] == 'ok')
            A(f'| {app} | {fn} | {len({r["size_n"] for r in rs})} | {okn}/{len(rs)} | ' + ' | '.join(cells) + ' |')
        A('| **geomean** | | | | ' + ' | '.join(f3(gm(allr[o])) for o in opts) + ' |')
        A('')

    gw = [k for k in kernels if any(idx.get((k['kernel'], 'gcc', o), {}).get('status') == 'WRONG' for o in opts)]
    if gw:
        A('## Configurations where the GCC build gives a wrong result on the simulator\n')
        A('These are left out of every geomean above (there is no correct GCC result to compare with). GCC\'s cycle count is still meaningful as a cost, because the wrong '
          'value comes from one instruction computing a different sign, not from a different amount of work, so the ratios are shown here for information. See "GCC f16 RFFT" in the analysis.\n')
        A('| app | function | type | sizes | clang status | ' + ' | '.join(f'-{o} clang/gcc cycles (info)' for o in opts) + ' |')
        A('|---|---|---|---|---|' + '---|' * len(opts))
        fg = collections.OrderedDict()
        for k in gw:
            fg.setdefault((k['app'], k['function'], k['dt']), []).append(k)
        for (app, fn, dt), ks in fg.items():
            cells, st = [], set()
            for o in opts:
                v = []
                for k in ks:
                    c, g = idx.get((k['kernel'], 'clang', o)), idx.get((k['kernel'], 'gcc', o))
                    if c:
                        st.add(c['status'])
                    if c and g and c['status'] == 'ok' and g.get('cycles'):
                        v.append(c['cycles'] / g['cycles'])
                cells.append(f3(gm(v)))
            A(f'| {app} | {fn} | {dt} | {len(ks)} | {", ".join(sorted(st))} | ' + ' | '.join(cells) + ' |')
        A('')
    fp = [r for r in rows if r['compiler'] == 'clang-fpon']
    if fp:
        A('## Experiment: clang with its own default `-ffp-contract=on`\n')
        A('All clang numbers above use `-ffp-contract=fast`, which the SDK flag wrapper adds to match GCC\'s default (multiply-adds are fused even across C statements). '
          'This table shows the same clang without that flag (fusion only inside one C expression). In no headline number.\n')
        A('| data type | n | correct (-O2) | bit-exact vs host (-O2): fast / on | bit-exact vs GCC (-O2): fast / on | geomean cycles on/fast: ' + ' / '.join('-' + o for o in opts) + ' |')
        A('|---|---|---|---|---|---|')
        for dt in ['fix16', 'f32', 'f16']:
            ks = [k for k in kernels if k['dt'] == dt]
            a = [idx.get((k['kernel'], 'clang', 'O2')) for k in ks]
            b = [idx.get((k['kernel'], 'clang-fpon', 'O2')) for k in ks]
            def cnt(rs, key):
                return sum(1 for r in rs if r and r['status'] == 'ok' and r.get(key))
            rat = []
            for o in opts:
                v = [idx[(k['kernel'], 'clang-fpon', o)]['cycles'] / idx[(k['kernel'], 'clang', o)]['cycles'] for k in ks
                     if idx.get((k['kernel'], 'clang-fpon', o), {}).get('status') == 'ok' and idx.get((k['kernel'], 'clang', o), {}).get('status') == 'ok']
                rat.append(f3(gm(v)))
            A(f'| {dt} | {len(ks)} | {sum(1 for r in b if r and r["status"] == "ok")} | {cnt(a, "exact_vs_host")} / {cnt(b, "exact_vs_host")} | '
              f'{cnt(a, "exact_vs_gcc")} / {cnt(b, "exact_vs_gcc")} | ' + ' / '.join(rat) + ' |')
        A('')
    an = R / 'analysis.txt'
    if an.exists():
        A(an.read_text())

    # ------------------------------------------------------------------ appendix
    A('## Appendix: every configuration\n')
    A('Cycles and retired instructions per call. `x` = clang/gcc.\n')
    A('| kernel | ' + ' | '.join(f'gcc -{o} cyc | clang -{o} cyc | x | gcc -{o} ins | clang -{o} ins' for o in opts) + ' | status |')
    A('|---|' + '---|---|---|---|---|' * len(opts) + '---|')
    for k in kernels:
        cells, st = [], set()
        for o in opts:
            c, g = idx.get((k['kernel'], 'clang', o)), idx.get((k['kernel'], 'gcc', o))
            cc, gc = (c or {}).get('cycles'), (g or {}).get('cycles')
            cells.append(f'{gc or "-"} | {cc or "-"} | {f3(ratio.get((k["kernel"], o)))} | {(g or {}).get("instrs") or "-"} | {(c or {}).get("instrs") or "-"}')
            for comp, r in (('clang', c), ('gcc', g)):
                if r and r['status'] != 'ok':
                    st.add(f'{comp} {r["status"]}')
                elif r and not r.get('exact_vs_host'):
                    st.add(f'{comp} tol')
        A(f'| {k["kernel"]} | ' + ' | '.join(cells) + f' | {"; ".join(sorted(st)) or "exact"} |')
    A('')
    (R / 'report.txt').write_text('\n'.join(L) + '\n')
    (R / 'summary.json').write_text(json.dumps(dict(
        fratio={' | '.join(map(str, k)): v for k, v in S['fratio'].items()}, size=S['size']), indent=1))
    return S


if __name__ == '__main__':
    R = pathlib.Path(__file__).resolve().parent
    write(R, json.loads((R / 'results.json').read_text()))
